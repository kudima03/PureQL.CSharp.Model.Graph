using System.Reflection;

namespace PureQL.CSharp.Model.Graph.Generator;

/// <summary>
/// Emits the writer and the reader of every model type as the partial class
/// <c>GraphMapping</c>, one file per model namespace and one for the enums, and the
/// entry point <c>QueryGraphs</c>. A record writer adds the record's node, sets its
/// scalar properties and links its children in constructor order; a record reader
/// calls the constructor with the values read back. A union writer and reader switch
/// over its cases, by runtime type and by node label.
/// </summary>
internal sealed class Emitter(ModelCatalog catalog, string modelVersion)
{
    private readonly ModelCatalog _catalog = catalog;

    private readonly string _modelVersion = modelVersion;

    public static string VersionOf(Assembly model)
    {
        string version =
            model
                .GetCustomAttribute<AssemblyInformationalVersionAttribute>()
                ?.InformationalVersion
            ?? model.GetName().Version!.ToString();
        int metadata = version.IndexOf('+', StringComparison.Ordinal);
        return metadata < 0 ? version : version[..metadata];
    }

    public SortedDictionary<string, string> Emit()
    {
        SortedDictionary<string, string> files = [with(StringComparer.Ordinal)];
        foreach (
            IGrouping<string, Type> group in _catalog
                .Records.Select(r => r.Type)
                .Concat(_catalog.Unions.Select(u => u.Type))
                .GroupBy(Namespace)
                .OrderBy(g => g.Key, StringComparer.Ordinal)
        )
        {
            files[$"GraphMapping.{group.Key}.g.cs"] = Mapping(group.Key);
        }

        files["GraphMapping.Enums.g.cs"] = Enums();
        files["QueryGraphs.g.cs"] = Entry();
        return files;
    }

    private static string Namespace(Type type)
    {
        string name = type.Namespace!;
        return name == typeof(PureQLQuery).Namespace
            ? "Queries"
            : name[(name.LastIndexOf('.') + 1)..];
    }

    private static string Literal(string text)
    {
        return $"\"{text}\"";
    }

    private CodeWriter Header(params string[] usings)
    {
        CodeWriter code = new CodeWriter();
        code.Line("// <auto-generated>");
        code.Line("// Generated by PureQL.CSharp.Model.Graph.Generator from");
        code.Line(
            $"// PureQL.CSharp.Model {_modelVersion}. Do not edit: change the generator"
        );
        code.Line("// and run it again.");
        code.Line("// </auto-generated>");
        code.Line("#nullable enable");
        code.Line();
        foreach (string name in usings)
        {
            code.Line($"using {name};");
        }

        if (usings.Length > 0)
        {
            code.Line();
        }

        code.Line("namespace PureQL.CSharp.Model.Graph;");
        code.Line();
        return code;
    }

    private string[] ModelUsings()
    {
        return
        [
            typeof(PureQLQuery).Namespace!,
            .. _catalog
                .Records.Select(r => r.Type.Namespace!)
                .Concat(_catalog.Unions.Select(u => u.Type.Namespace!))
                .Where(n => n != typeof(PureQLQuery).Namespace)
                .Distinct()
                .Order(StringComparer.Ordinal),
        ];
    }

    private string Mapping(string ns)
    {
        CodeWriter code = Header(ModelUsings());
        code.Open("internal static partial class GraphMapping");
        bool first = true;
        foreach (
            RecordModel record in _catalog.Records.Where(r => Namespace(r.Type) == ns)
        )
        {
            Separate(code, ref first);
            RecordWriter(code, record);
            code.Line();
            RecordReader(code, record);
        }

        foreach (UnionModel union in _catalog.Unions.Where(u => Namespace(u.Type) == ns))
        {
            Separate(code, ref first);
            if (union.Scalar is null)
            {
                UnionWriter(code, union);
                code.Line();
                UnionReader(code, union);
            }
            else
            {
                ScalarUnionWriter(code, union);
                code.Line();
                ScalarUnionReader(code, union);
            }
        }

        code.Close();
        return code.ToString();
    }

    private static void Separate(CodeWriter code, ref bool first)
    {
        if (!first)
        {
            code.Line();
        }

        first = false;
    }

    private static void RecordWriter(CodeWriter code, RecordModel record)
    {
        string name = record.Type.Name;
        code.Call(
            $"internal static int Write{name}",
            ["GraphBuilder graph", $"{name} value"],
            ""
        );
        code.Block();
        code.Wrap("int node = ", $"graph.Add({Literal(name)});", "");
        foreach (PropertyModel property in record.Properties)
        {
            string access = $"value.{property.Name}";
            string parameter = Literal(property.Parameter);
            string relationship = Literal(property.Name);
            string item = property.Type.Name;
            switch (property.Kind)
            {
                case PropertyKind.Scalar:
                case PropertyKind.Scalars:
                    code.Call("graph.Set", ["node", parameter, access], ";");
                    break;
                case PropertyKind.OptionalScalar:
                case PropertyKind.OptionalScalars:
                    code.Call("graph.SetOptional", ["node", parameter, access], ";");
                    break;
                case PropertyKind.Enum:
                    code.Call(
                        "graph.Set",
                        ["node", parameter, $"Write{item}({access})"],
                        ";"
                    );
                    break;
                case PropertyKind.Child when ModelCatalog.IsUnion(property.Type):
                    code.Call(
                        "graph.Link",
                        ["node", relationship, $"Write{item}(graph, {access})"],
                        ";"
                    );
                    break;
                case PropertyKind.Child:
                    code.Call(
                        "graph.Link",
                        ["node", relationship, parameter, access, $"Write{item}"],
                        ";"
                    );
                    break;
                case PropertyKind.OptionalChild:
                    code.Open($"if ({access}.HasValue)");
                    code.Call(
                        "graph.Link",
                        ["node", relationship, $"Write{item}(graph, {access}.Value)"],
                        ";"
                    );
                    code.Close();
                    code.Line();
                    break;
                case PropertyKind.Many:
                    code.Call(
                        "graph.Many",
                        ["node", relationship, parameter, access, $"Write{item}"],
                        ";"
                    );
                    break;
                case PropertyKind.OptionalMany:
                    code.Call(
                        "graph.ManyOptional",
                        ["node", relationship, parameter, access, $"Write{item}"],
                        ";"
                    );
                    break;
                case PropertyKind.ScalarUnion:
                    code.Call(
                        $"Write{item}",
                        ["graph", "node", parameter, relationship, access],
                        ";"
                    );
                    break;
                default:
                    throw new InvalidOperationException(
                        $"{property.Kind} is not written."
                    );
            }
        }

        code.Line("return node;");
        code.Close();
    }

    private static void RecordReader(CodeWriter code, RecordModel record)
    {
        string name = record.Type.Name;
        code.Call($"internal static {name} Read{name}", ["IReadNode node"], "");
        code.Block();
        code.Call($"return new {name}", [.. record.Properties.Select(Read)], ";");
        code.Close();
    }

    private static string Read(PropertyModel property)
    {
        string parameter = Literal(property.Parameter);
        string relationship = Literal(property.Name);
        string item = property.Type.Name;
        return property.Kind switch
        {
            PropertyKind.Scalar =>
                $"GraphReads.{ModelCatalog.Scalars[property.Type]}(node, {parameter})",
            PropertyKind.OptionalScalar =>
                $"GraphReads.Optional{ModelCatalog.Scalars[property.Type]}(node, {parameter})",
            PropertyKind.Scalars =>
                $"GraphReads.{ModelCatalog.Lists[property.Type]}(node, {parameter})",
            PropertyKind.OptionalScalars =>
                $"GraphReads.Optional{ModelCatalog.Lists[property.Type]}(node, {parameter})",
            PropertyKind.Enum => $"Read{item}(node, {parameter}, "
                + (property.Default is null ? "null" : $"{item}.{property.Default}")
                + ")",
            PropertyKind.Child => $"Read{item}(GraphReads.Child(node, {relationship}))",
            PropertyKind.OptionalChild =>
                $"GraphReads.Optional(node, {relationship}, Read{item})",
            PropertyKind.Many => $"GraphReads.Many(node, {relationship}, Read{item})",
            PropertyKind.OptionalMany =>
                $"GraphReads.ManyOptional(node, {relationship}, {parameter}, Read{item})",
            PropertyKind.ScalarUnion => $"Read{item}(node, {parameter}, {relationship})",
            _ => throw new InvalidOperationException($"{property.Kind} is not read."),
        };
    }

    private static void UnionWriter(CodeWriter code, UnionModel union)
    {
        string name = union.Type.Name;
        code.Call(
            $"internal static int Write{name}",
            ["GraphBuilder graph", $"{name} value"],
            ""
        );
        code.Block();
        code.Line("return value.Value switch");
        code.Line("{");
        code.Indent();
        foreach (Type item in union.Cases)
        {
            code.Line($"{item.Name} item => Write{item.Name}(graph, item),");
        }

        code.Line($"_ => throw GraphBuilder.Empty({Literal(name)}),");
        code.Outdent();
        code.Line("};");
        code.Close();
    }

    private static void UnionReader(CodeWriter code, UnionModel union)
    {
        string name = union.Type.Name;
        code.Call($"internal static {name} Read{name}", ["IReadNode node"], "");
        code.Block();
        code.Line("return node.Label switch");
        code.Line("{");
        code.Indent();
        foreach (Type item in union.Cases)
        {
            code.Wrap(
                $"{Literal(item.Name)} => ",
                $"new {name}(Read{item.Name}(node)),",
                ""
            );
        }

        code.Line($"_ => throw GraphReads.NotACase(node, {Literal(name)}),");
        code.Outdent();
        code.Line("};");
        code.Close();
    }

    /// <summary>
    /// Writes a union with a scalar case on the node that holds it: the scalar as a
    /// property, a record case as a relationship.
    /// </summary>
    private static void ScalarUnionWriter(CodeWriter code, UnionModel union)
    {
        string name = union.Type.Name;
        code.Call(
            $"internal static void Write{name}",
            [
                "GraphBuilder graph",
                "int node",
                "string name",
                "string type",
                $"{name} value",
            ],
            ""
        );
        code.Block();
        code.Open("switch (value.Value)");
        foreach (Type item in union.Cases)
        {
            bool scalar = item == union.Scalar;
            string alias = scalar ? CSharpName(item) : item.Name;
            code.Line($"case {alias} item:");
            code.Indent();
            code.Line(
                scalar
                    ? "graph.Set(node, name, item);"
                    : $"graph.Link(node, type, Write{item.Name}(graph, item));"
            );
            code.Line("break;");
            code.Outdent();
        }

        code.Line("default:");
        code.Indent();
        code.Line($"throw GraphBuilder.Empty({Literal(name)});");
        code.Outdent();
        code.Close();
        code.Close();
    }

    private static void ScalarUnionReader(CodeWriter code, UnionModel union)
    {
        string name = union.Type.Name;
        string scalar = ModelCatalog.Scalars[union.Scalar!];
        code.Call(
            $"internal static {name} Read{name}",
            ["IReadNode node", "string name", "string type"],
            ""
        );
        code.Block();
        code.Open("if (GraphReads.Has(node, name))");
        code.Line($"return new {name}(GraphReads.{scalar}(node, name));");
        code.Close();
        code.Line();
        code.Line("IReadNode child = GraphReads.Child(node, type);");
        code.Line("return child.Label switch");
        code.Line("{");
        code.Indent();
        foreach (Type item in union.Cases.Where(c => c != union.Scalar))
        {
            code.Wrap(
                $"{Literal(item.Name)} => ",
                $"new {name}(Read{item.Name}(child)),",
                ""
            );
        }

        code.Line($"_ => throw GraphReads.NotACase(child, {Literal(name)}),");
        code.Outdent();
        code.Line("};");
        code.Close();
    }

    private static string Article(string name)
    {
        return ("AEIOU".Contains(name[0], StringComparison.Ordinal) ? "an " : "a ")
            + name;
    }

    private static string CSharpName(Type scalar)
    {
        return scalar == typeof(string) ? "string"
            : scalar == typeof(long) ? "long"
            : scalar == typeof(bool) ? "bool"
            : scalar == typeof(decimal) ? "decimal"
            : scalar.Name;
    }

    private string Enums()
    {
        CodeWriter code = Header([
            .. _catalog
                .Enums.Select(e => e.Namespace!)
                .Distinct()
                .Order(StringComparer.Ordinal),
        ]);
        code.Open("internal static partial class GraphMapping");
        bool first = true;
        foreach (Type type in _catalog.Enums)
        {
            string name = type.Name;
            string[] values = Enum.GetNames(type);
            Separate(code, ref first);
            code.Open($"internal static string Write{name}({name} value)");
            code.Line("return value switch");
            code.Line("{");
            code.Indent();
            foreach (string value in values)
            {
                code.Line($"{name}.{value} => {Literal(value)},");
            }

            code.Wrap(
                "_ => throw new GraphMappingException(",
                $"$\"{{value}} is not {Article(name)}.\"),",
                ""
            );
            code.Outdent();
            code.Line("};");
            code.Close();
            code.Line();
            code.Call(
                $"internal static {name} Read{name}",
                ["IReadNode node", "string name", $"{name}? absent"],
                ""
            );
            code.Block();
            code.Line("return GraphReads.OptionalString(node, name) switch");
            code.Line("{");
            code.Indent();
            code.Line("null => absent ?? throw GraphReads.Missing(node, name),");
            foreach (string value in values)
            {
                code.Line($"{Literal(value)} => {name}.{value},");
            }

            code.Line($"_ => throw GraphReads.NotA(node, name, \"{Article(name)}\"),");
            code.Outdent();
            code.Line("};");
            code.Close();
        }

        code.Close();
        return code.ToString();
    }

    private string Entry()
    {
        string root = _catalog.Root.Name;
        CodeWriter code = Header(_catalog.Root.Namespace!);
        code.Line("/// <summary>");
        code.Line(
            "/// Writes a query as a property graph and reads one back: one node per model"
        );
        code.Line(
            "/// record, labelled with the record's name and <see cref=\"GraphLabels.Node\"/>,"
        );
        code.Line(
            "/// and one relationship per child, typed with the model property that holds it."
        );
        code.Line("/// </summary>");
        code.Open("public static class QueryGraphs");
        code.Line("/// <summary>The graph of a query.</summary>");
        code.Line("/// <param name=\"query\">The query.</param>");
        code.Line(
            "/// <param name=\"id\">The query's identifier, on every node.</param>"
        );
        code.Line(
            "/// <returns>The nodes and relationships; node 0 is the root.</returns>"
        );
        code.Line("/// <exception cref=\"GraphMappingException\">");
        code.Line("/// The query leaves a required value missing.");
        code.Line("/// </exception>");
        code.Open($"public static QueryGraph Of({root} query, Guid id)");
        code.Line("GraphBuilder graph = new GraphBuilder(id);");
        code.Line($"_ = GraphMapping.Write{root}(graph, query);");
        code.Line("return graph.Graph();");
        code.Close();
        code.Line();
        code.Line("/// <summary>A query read back from its graph.</summary>");
        code.Line("/// <param name=\"root\">The root node of the query's graph.</param>");
        code.Line("/// <returns>The query.</returns>");
        code.Line("/// <exception cref=\"GraphMappingException\">");
        code.Line(
            "/// A node, relationship or property is missing or not what the model expects."
        );
        code.Line("/// </exception>");
        code.Open($"public static {root} Read(IReadNode root)");
        code.Line("ArgumentNullException.ThrowIfNull(root);");
        code.Line($"return GraphMapping.Read{root}(root);");
        code.Close();
        code.Close();
        return code.ToString();
    }
}
